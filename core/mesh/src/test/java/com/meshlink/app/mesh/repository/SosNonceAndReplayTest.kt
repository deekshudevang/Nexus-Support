            clock = clockTime
        )
    }

    /**
     * PROOF: Birthday bound collision probability formula for 1-byte nonce (S = 256).
     *
     * Exact formula: P(collision) = 1 - product_{k=0}^{n-1} (1 - k/256)
     */
    @Test
    fun `prove birthday bound collision probability for 1-byte nonce`() {
        fun collisionProbability(n: Int, s: Int = 256): Double {
            var probNoCollision = 1.0
            for (k in 0 until n) {
                probNoCollision *= (s - k).toDouble() / s.toDouble()
            }
            return 1.0 - probNoCollision
        }

        val p2 = collisionProbability(2)
        val p10 = collisionProbability(10)
        val p19 = collisionProbability(19)
        val p20 = collisionProbability(20)
        val p30 = collisionProbability(30)

        assertEquals(1.0 / 256.0, p2, 0.0001)
        assertTrue("p10 should be ~16.26%", p10 in 0.16..0.17)
        assertTrue("p19 should be ~49.86%", p19 in 0.49..0.50)
        assertTrue("p20 must cross 50% threshold (53.41%)", p20 > 0.50 && p20 < 0.55)
        assertTrue("p30 should be ~83.19%", p30 in 0.82..0.85)
    }

    /**
     * Simulation with a fixed seed (Random(42L)) drawing n=20 samples from S=256 across 10,000 trials.
     * Validates that empirical collision rate matches the theoretical 53.4% +/- 2%.
     */
    @Test
    fun `simulation with fixed seed confirms 1-byte nonce collision exceeds 50 percent for 20 emissions`() {
        val seed = 42L
        val rng = Random(seed)
        val numTrials = 10_000
        val sampleSize = 20
        var collisionCount = 0

        repeat(numTrials) {
            val seen = BooleanArray(256)
            var hadCollision = false
            for (i in 0 until sampleSize) {
                val value = rng.nextInt(256)
                if (seen[value]) {
                    hadCollision = true
                    break
                }
                seen[value] = true
            }
            if (hadCollision) collisionCount++
        }

        val empiricalProbability = collisionCount.toDouble() / numTrials.toDouble()
        // Theoretical value is ~0.5341. With 10,000 trials, should be well within [0.51, 0.56].
        assertTrue(
            "Empirical collision probability ($empiricalProbability) must be near theoretical 53.4%",
            empiricalProbability in 0.51..0.56
        )
    }

    /**
     * Quantify collision probability across distinct senders in an area:
     * 32-bit CRC32 device hash + 8-bit nonce = 40-bit state space per 1-second delta.
     * N_50% ≈ sqrt(2 * ln(2) * 2^40) ≈ 1,232,875 concurrent senders.
     */
    @Test
    fun `quantify collision probability across distinct senders in an area`() {
        val bits = 40.0
        val totalStates = Math.pow(2.0, bits) // ~1.0995 x 10^12
        val nFiftyPercent = Math.sqrt(2.0 * Math.log(2.0) * totalStates)

        // Verifies that over 1.2 million senders emitting in the exact same 1s delta are required for 50% collision
        assertTrue("50% collision across senders requires > 1.2M devices", nFiftyPercent > 1_200_000.0)
        assertTrue("50% collision across senders requires < 1.3M devices", nFiftyPercent < 1_300_000.0)
    }

    @Test
    fun `nonce generator produces values across wraparound without exception`() {
        val generator = SosNonceGenerator()
        val nonces = mutableListOf<Byte>()

        repeat(300) {
            nonces.add(generator.nextNonce())
        }

        assertEquals(300, nonces.size)
        assertTrue(nonces.any { it > 0 })
        assertTrue(nonces.any { it < 0 })
    }

    @Test
    fun `seen message cache suppresses replay inside 10-minute TTL using injectable clock`() {
        var clockTime = 1_000_000L
        val cache = SeenMessageCache(clock = { clockTime })
        val beaconId = "sos-12345678-500-42"

        assertFalse("Initially unseen", cache.isAlreadySeen(beaconId, isCritical = true))
        cache.markSeen(beaconId)
        assertTrue("Seen immediately after marking", cache.isAlreadySeen(beaconId, isCritical = true))

        // Advance clock by 5 minutes (within 10-minute TTL)
        clockTime += 5 * 60 * 1_000L
        assertTrue("Replay inside 5 minutes is suppressed", cache.isAlreadySeen(beaconId, isCritical = true))

        // Advance clock to 9 minutes 59 seconds
        clockTime += (4 * 60 + 59) * 1_000L
        assertTrue("Replay just before 10 minutes is suppressed", cache.isAlreadySeen(beaconId, isCritical = true))
    }

    @Test
    fun `seen message cache allows retransmission after 10-minute TTL expiry using injectable clock`() {
        var clockTime = 1_000_000L
        val cache = SeenMessageCache(clock = { clockTime })
        val beaconId = "sos-12345678-500-42"

        cache.markSeen(beaconId)
        assertTrue("Seen initially", cache.isAlreadySeen(beaconId, isCritical = true))

        // Advance clock by 10 minutes and 1 second (past 10-minute TTL)
        clockTime += (10 * 60 + 1) * 1_000L

        // Defined behavior: entry has expired its TTL and is treated as unseen
        assertFalse(
            "Treated as unseen after TTL expiry, allowing emergency retransmission",
            cache.isAlreadySeen(beaconId, isCritical = true)
        )
    }

    @Test
    fun `process restart resets in-memory seen message cache but real DB guarantees restart durability`() = runTest {
        // Step 1: Initial process lifetime with Router 1
        var processTime = 1_000_000L
        val router1 = createMeshRouter(clockTime = { processTime })

        val sosUuid = "sos-uuid-auth-durable-999"
        val packet = MeshPacket(
            messageId = sosUuid,
            senderId = senderDeviceId,
            receiverId = myDeviceId,
            content = """{"uuid":"$sosUuid","emergencyType":"MEDICAL","severity":"CRITICAL","message":"Help"}""",
            timestamp = processTime,
            type = PacketType.SOS,
            originId = senderDeviceId,
            finalDestId = myDeviceId,
            hopCount = 0,
            maxHops = 10,
            priority = 10
        )

        // Deliver authenticated SOS to Router 1
        val result1 = router1.route(senderDeviceId, packet, mapOf(senderDeviceId to senderDeviceId))
        assertTrue(result1 is RoutingResult.Processed)

        // Verify exactly 1 alert persisted in Room database
        val messagesAfter1 = messageRepository.getAllMessages()
        assertEquals("Exactly 1 alert in DB", 1, messagesAfter1.size)
        assertEquals(sosUuid, messagesAfter1.first().id)

        // Step 2: Simulate process kill and cold start:
        // A fresh Router 2 instance is created with brand new, empty in-memory caches,
        // but bound to the SAME underlying persisted database instance.
        val router2 = createMeshRouter(clockTime = { processTime + 5_000L })

        // The replayed packet arrives again at router2
        val result2 = router2.route(senderDeviceId, packet, mapOf(senderDeviceId to senderDeviceId))
        assertTrue(result2 is RoutingResult.Processed)

        // Invariant: The database alert count MUST REMAIN 1 (durable deduplication via @PrimaryKey id)
        val messagesAfterRestart = messageRepository.getAllMessages()
        assertEquals(
            "Restart durability: primary key uniqueness prevents duplicate alert across process restart",
            1,
            messagesAfterRestart.size
        )
        assertEquals(sosUuid, messagesAfterRestart.first().id)
    }

    @Test
    fun `per-source rate limiting drops beacon flood from single source`() = runTest {
        val router = createMeshRouter()

        fun makeBeaconPacket(delta: Int, nonce: Byte): MeshPacket = MeshPacket(
            messageId = "sos-$senderDeviceHash-$delta-$nonce",
            senderId = "sos-beacon",
            receiverId = myDeviceId,
            content = """{"emergencyType":"MEDICAL","severity":"CRITICAL"}""",
            timestamp = simulatedTimeMs,
            type = PacketType.SOS,
            originId = senderDeviceHash.toString(),
            finalDestId = myDeviceId,
            hopCount = 0,
            maxHops = 1,
            priority = 10
        )

        // 1st beacon accepted
        val res1 = router.route("sos-beacon", makeBeaconPacket(100, 1), emptyMap())
        assertTrue("First beacon accepted", res1 is RoutingResult.Processed)

        // Immediate subsequent beacons within 2-second rate limit window from same source hash are DROPPED
        val res2 = router.route("sos-beacon", makeBeaconPacket(100, 2), emptyMap())
        assertTrue("Immediate second beacon dropped by per-source rate limit", res2 is RoutingResult.Drop)

        val res3 = router.route("sos-beacon", makeBeaconPacket(100, 3), emptyMap())
        assertTrue("Immediate third beacon dropped by per-source rate limit", res3 is RoutingResult.Drop)

        // Advance simulated time by 2.5 seconds (past per-source interval)
        simulatedTimeMs += 2_500L
        val res4 = router.route("sos-beacon", makeBeaconPacket(102, 4), emptyMap())
        assertTrue("Beacon after 2.5s accepted", res4 is RoutingResult.Processed)
    }

    @Test
    fun `global sliding window rate limiting bounds unverified beacons to 30 per minute`() = runTest {
        val router = createMeshRouter()

        var acceptedCount = 0
        var droppedCount = 0

        // Send 40 unique beacons from 40 distinct sender device hashes within a 10-second span
        for (i in 1..40) {
            val devHash = 0x10000000 + i
            val packet = MeshPacket(
                messageId = "sos-$devHash-500-$i",
                senderId = "sos-beacon",
                receiverId = myDeviceId,
                content = """{"emergencyType":"MEDICAL","severity":"CRITICAL"}""",
                timestamp = simulatedTimeMs,
                type = PacketType.SOS,
                originId = devHash.toString(),
                finalDestId = myDeviceId,
                hopCount = 0,
                maxHops = 1,
                priority = 10
            )
            simulatedTimeMs += 100L // 100ms between arrivals
            val res = router.route("sos-beacon", packet, emptyMap())
            if (res is RoutingResult.Processed) acceptedCount++
            if (res is RoutingResult.Drop) droppedCount++
        }

        assertEquals("Global rate limiter allows exactly 30 beacons per minute", 30, acceptedCount)
        assertEquals("Remaining 10 excess beacons are dropped", 10, droppedCount)
    }

    @Test
    fun `colliding unauthenticated beacon cannot suppress authenticated SOS event`() = runTest {
        val router = createMeshRouter()

        val collidingId = "sos-colliding-event-key"
        val beaconPacket = MeshPacket(
            messageId = collidingId,
            senderId = "sos-beacon",
            receiverId = myDeviceId,
            content = """{"emergencyType":"MEDICAL","severity":"CRITICAL"}""",
            timestamp = simulatedTimeMs,
            type = PacketType.SOS,
            originId = "999999",
            finalDestId = myDeviceId,
            hopCount = 0,
            maxHops = 1,
            priority = 10
        )

        // 1. Deliver unauthenticated beacon with collidingId
        val beaconResult = router.route("sos-beacon", beaconPacket, emptyMap())
        assertTrue("Beacon processed as unverified", beaconResult is RoutingResult.Processed)

        // 2. Deliver an authenticated mesh SOS packet with the same messageId (or carrying it)
        simulatedTimeMs += 500L
        val authPacket = MeshPacket(
            messageId = collidingId,
            senderId = senderDeviceId,
            receiverId = myDeviceId,
            content = """{"uuid":"$collidingId","emergencyType":"FIRE","severity":"CRITICAL","message":"Help me"}""",
            timestamp = simulatedTimeMs,
            type = PacketType.SOS,
            originId = senderDeviceId,
            finalDestId = myDeviceId,
            hopCount = 0,
            maxHops = 10,
            priority = 10
        )

        val authResult = router.route(senderDeviceId, authPacket, mapOf(senderDeviceId to senderDeviceId))
        // INVARIANT: Authenticated SOS packet MUST NOT be dropped by the preceding beacon!
        assertTrue(
            "Authenticated SOS must never be suppressed by a colliding unauthenticated beacon",
            authResult is RoutingResult.Processed
        )

        // Both are preserved or the authenticated alert exists in Room
        val dbMessages = messageRepository.getAllMessages()
        assertTrue("Room contains authenticated alert", dbMessages.any { it.id == collidingId })
    }

    @Test
    fun `hard memory bound and TTL pruning on unverified beacon alert records`() = runTest {
        val router = createMeshRouter()

        // Deliver 25 beacons spaced by 2.1s (satisfies per-source and global rate limits)
        for (i in 1..25) {
            val devHash = 0x20000000 + i
            simulatedTimeMs += 2_100L
            val packet = MeshPacket(
                messageId = "sos-$devHash-100-1",
                senderId = "sos-beacon",
                receiverId = myDeviceId,
                content = """{"emergencyType":"MEDICAL","severity":"CRITICAL"}""",
                timestamp = simulatedTimeMs,
                type = PacketType.SOS,
                originId = devHash.toString(),
                finalDestId = myDeviceId,
                hopCount = 0,
                maxHops = 1,
                priority = 10
            )
            val res = router.route("sos-beacon", packet, emptyMap())
            assertTrue(res is RoutingResult.Processed)
        }

        // Advance simulated time past 10 minutes (TTL expiry for beacon records)
        simulatedTimeMs += 11 * 60 * 1_000L

        // Deliver 1 new beacon
        val devHashNew = 0x30000001
        val newPacket = MeshPacket(
            messageId = "sos-$devHashNew-200-1",
            senderId = "sos-beacon",
            receiverId = myDeviceId,
            content = """{"emergencyType":"MEDICAL","severity":"CRITICAL"}""",
            timestamp = simulatedTimeMs,
            type = PacketType.SOS,
            originId = devHashNew.toString(),
            finalDestId = myDeviceId,
            hopCount = 0,
            maxHops = 1,
            priority = 10
        )
        val resNew = router.route("sos-beacon", newPacket, emptyMap())
        assertTrue("New beacon accepted and expired records purged", resNew is RoutingResult.Processed)
    }
