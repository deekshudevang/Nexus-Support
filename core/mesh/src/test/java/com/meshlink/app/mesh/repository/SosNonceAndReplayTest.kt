package com.meshlink.app.mesh.repository

import com.meshlink.app.mesh.routing.SeenMessageCache
import com.meshlink.app.mesh.transport.SosBeaconCodec
import com.meshlink.app.mesh.transport.SosNonceGenerator
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.util.UUID

/**
 * Proof and verification tests for Defect N4: Nonce & Replay protection.
 *
 * Production Identity Specification:
 * 1. Beacon ID format: "sos-<deviceIdHash>-<timestampDelta>-<nonce>"
 *    - deviceIdHash: 32-bit CRC32 hash of sender device ID (4 bytes)
 *    - timestampDelta: 16-bit unsigned delta relative to UTC midnight (2 bytes)
 *    - nonce: 8-bit per-activation value from [SosNonceGenerator] (1 byte)
 * 2. Structured Mesh SOS format: RFC 4122 random UUID (128-bit)
 * 3. Generation path:
 *    - Beacon nonce is generated by a single path: [SosNonceGenerator.nextNonce()]
 *      called during [NearbyRepositoryImpl.sendSos()].
 * 4. Replay and Deduplication State:
 *    - Ephemeral state lives in [SeenMessageCache] (LRU capacity = 200, TTL = 10 minutes,
 *      Bloom filter = 10,000 entries, 1% false positive rate).
 *    - In-memory only: process restart clears [SeenMessageCache]. Persistent deduplication
 *      relies on the database alert uniqueness constraints.
 */
class SosNonceAndReplayTest {

    /**
     * PROOF: Birthday bound collision probability for 1-byte nonce (S = 256).
     *
     * Exact formula for collision probability with n choices from S=256:
     *   P(collision) = 1 - product_{k=0}^{n-1} (1 - k/256)
     *
     * Results:
     *   n = 2:  P ≈ 0.39%
     *   n = 10: P ≈ 16.26%
     *   n = 19: P ≈ 49.86% (~50% crossover)
     *   n = 20: P ≈ 53.41% (>50%)
     *   n = 30: P ≈ 83.19%
     *
     * Conclusion:
     * A 1-byte nonce alone CANNOT guarantee uniqueness across activations.
     * True uniqueness requires the composite key (deviceIdHash, timestampDelta, nonce)
     * and the authoritative 128-bit mesh UUID channel.
     */
    @Test
    fun `prove birthday bound collision probability for 1-byte nonce`() {
        fun collisionProbability(n: Int, s: Int = 256): Double {
            var probNoCollision = 1.0
            for (k in 0 until n) {
                probNoCollision *= (s - k).toDouble() / s.toDouble()
            }
            return 1.0 - probNoCollision
        }

        val p2 = collisionProbability(2)
        val p10 = collisionProbability(10)
        val p19 = collisionProbability(19)
        val p20 = collisionProbability(20)
        val p30 = collisionProbability(30)

        // Verify mathematical properties
        assertEquals(1.0 / 256.0, p2, 0.0001)
        assertTrue("p10 should be ~16%", p10 in 0.16..0.17)
        assertTrue("p20 must cross 50% threshold", p20 > 0.50)
        assertTrue("p30 should be ~82%", p30 in 0.80..0.85)
    }

    @Test
    fun `nonce generator produces values across wraparound without exception`() {
        val generator = SosNonceGenerator()
        val nonces = mutableListOf<Byte>()

        // Generate 300 nonces (more than the 256 byte range)
        repeat(300) {
            nonces.add(generator.nextNonce())
        }

        assertEquals(300, nonces.size)
        // Ensure values exist across positive and negative byte ranges
        assertTrue(nonces.any { it > 0 })
        assertTrue(nonces.any { it < 0 })
    }

    @Test
    fun `seen message cache deduplicates identical beacon within window`() {
        val cache = SeenMessageCache()
        val beaconId = "sos-12345678-500-42"

        assertFalse("Initially unseen", cache.isAlreadySeen(beaconId))
        cache.markSeen(beaconId)
        assertTrue("Seen immediately after marking", cache.isAlreadySeen(beaconId))
    }

    @Test
    fun `process restart resets in-memory seen message cache`() {
        val cache1 = SeenMessageCache()
        val beaconId = "sos-87654321-100-99"

        cache1.markSeen(beaconId)
        assertTrue("Seen in process 1", cache1.isAlreadySeen(beaconId))

        // Simulate process death and cold start
        val restartedCache = SeenMessageCache()
        assertFalse("Unseen in fresh process instance after restart", restartedCache.isAlreadySeen(beaconId))
    }

    @Test
    fun `collision case causes beacon suppression in seen cache`() {
        val cache = SeenMessageCache()
        val deviceIdHash = 0x12345678
        val delta = 1000
        val collidingNonce: Byte = 0x7F

        val beaconAId = "sos-$deviceIdHash-$delta-$collidingNonce"
        val beaconBId = "sos-$deviceIdHash-$delta-$collidingNonce" // Simulated collision

        cache.markSeen(beaconAId)
        // Beacon B has identical ID, so cache treats it as duplicate
        assertTrue("Colliding beacon is suppressed by dedup cache", cache.isAlreadySeen(beaconBId))
    }

    @Test
    fun `cache handles high volume flooding safely`() {
        val cache = SeenMessageCache()

        // Flood 5,000 distinct message IDs
        for (i in 0 until 5000) {
            val id = "flood-msg-$i"
            cache.markSeen(id)
        }

        // The most recently added entry must still be seen
        assertTrue(cache.isAlreadySeen("flood-msg-4999"))
    }
}
