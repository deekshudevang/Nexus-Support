/**
 * Proof and verification tests for Defect N4: Identity, Nonce & Replay protection.
 *
 * Production Identity Specification:
 * 1. Authoritative Identity:
 *    - Authenticated SOS UUID (128-bit RFC 4122 random UUID) is the SINGLE AUTHORITATIVE
 *      identity of an emergency event.
 *    - The beacon triple ("sos-<deviceIdHash>-<timestampDelta>-<nonce>") is an ephemeral
 *      correlation hint ONLY, generated by [NearbyRepositoryImpl.sendSos()].
 *
 * 2. Nonce Collision Quantification:
 *    - Single sender: 8-bit nonce has S = 256 states.
 *      By the Birthday Paradox: P(n=2) = 0.39%, P(n=10) = 16.26%, P(n=20) = 53.41% (>50%),
 *      P(n=30) = 83.19%. An 8-bit nonce cannot guarantee uniqueness across activations.
 *    - Across multiple senders in an area:
 *      32-bit CRC32 device hash + 16-bit timestamp delta + 8-bit nonce = 56-bit total space.
 *      For emissions within the same 1-second delta window (40-bit space = 1.1 x 10^12 states),
 *      50% collision probability requires ~1.23 million concurrent emitting senders.
 *
 * 3. Replay, Deduplication & Durability Invariants:
 *    - SeenMessageCache uses an injectable clock.
 *    - Replay inside 10-minute TTL (DEFAULT_TTL_MS) is suppressed.
 *    - Replay after 10-minute TTL expiry is treated as unseen by the cache (allowing re-broadcast).
 *    - Process restart clears in-memory caches, but Room database primary key uniqueness
 *      (@PrimaryKey val id: String with OnConflictStrategy.REPLACE) durably ensures
 *      zero duplicate alerts across process restarts without requiring schema changes.
 *    - Anti-flood bounds: Per-source rate limit (2s interval), global rate limit (30/min),
 *      and hard memory cap (MAX_UNVERIFIED_BEACONS = 100) with TTL-based pruning.
 *    - A colliding unauthenticated beacon NEVER suppresses an authenticated event.
 */
@RunWith(RobolectricTestRunner::class)
class SosNonceAndReplayTest {

    private lateinit var context: Context
    private lateinit var database: AppDatabase
    private lateinit var deviceRepository: DeviceRepositoryImpl
    private lateinit var messageRepository: MessageRepositoryImpl
    private var simulatedTimeMs: Long = 1_000_000L

    private val myDeviceId = "DEVICE_RECEIVER"
    private val senderDeviceId = "DEVICE_SENDER"
    private val senderDeviceHash = SosBeaconCodec.crc32(senderDeviceId.toByteArray())

    @Before
