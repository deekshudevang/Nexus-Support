"""Comprehensive PostgreSQL Live Verification Script for Milestone M3.14.

Validates:
1. Real PostgreSQL connection and server version.
2. Alembic migration tables, relations, and constraints.
3. Transactional incident lifecycle and check constraints.
4. Partial unique indexes and responder dispatch assignments.
5. Transactional outbox event persistence with FOR UPDATE SKIP LOCKED.
6. Real FastAPI endpoints backed by live PostgreSQL.
7. Container restart & auto-reconnect recovery.
8. Live pg_dump backup and pg_restore integrity check.
"""

import os
import sys
import time
import uuid
import subprocess
from sqlalchemy import create_engine, text, inspect
from sqlalchemy.orm import sessionmaker

PG_URL = os.getenv("DATABASE_URL", "postgresql+psycopg2://rescuemesh:rescuemesh_dev_secret@localhost:5432/rescuemesh")
os.environ["DATABASE_URL"] = PG_URL

from app.core.database import Base
from app.models.incident import IncidentModel
from app.models.responder import ResponderModel
from app.models.team import TeamModel
from app.models.team_member import TeamMemberModel
from app.models.assignment import AssignmentModel
from app.models.outbox_event import OutboxEventModel
from app.models.stream_event import StreamEventModel
from app.models.user import UserModel
from app.services.outbox_publisher import process_outbox_batch
from main import app
from fastapi.testclient import TestClient
from app.core.rbac import create_access_token
from app.core.security import hash_password

results = []

def record(name: str, passed: bool, details: str):
    results.append({"name": name, "passed": passed, "details": details})
    symbol = "[PASS]" if passed else "[FAIL]"
    print(f"{symbol} {name}: {details}")

def main():
    print("=" * 70)
    print("STARTING NEXUS-SUPPORT REAL POSTGRESQL VERIFICATION (M3.14)")
    print(f"Target Database URL: {PG_URL}")
    print("=" * 70)

    # 1. Connection & Server Info
    engine = create_engine(PG_URL, pool_pre_ping=True)
    Session = sessionmaker(bind=engine)

    try:
        with engine.connect() as conn:
            version_str = conn.execute(text("SELECT version();")).scalar()
            current_db = conn.execute(text("SELECT current_database();")).scalar()
            record("1. Connection & Version", True, f"Connected to {current_db}. PostgreSQL version: {version_str[:38]}...")
    except Exception as e:
        record("1. Connection & Version", False, str(e))
        return

    # 2. Schema and Tables Verification
    expected_tables = {
        "alembic_version", "assignments", "audit_logs", "devices",
        "idempotency_keys", "incident_events", "incident_links", "incidents",
        "node_status", "outbox_events", "responders", "sos_packets",
        "stream_events", "team_members", "teams", "users"
    }
    try:
        inspector = inspect(engine)
        actual_tables = set(inspector.get_table_names())
        missing = expected_tables - actual_tables
        if missing:
            record("2. Schema Table Audit", False, f"Missing tables: {missing}")
        else:
            record("2. Schema Table Audit", True, f"All {len(expected_tables)} expected tables present in public schema.")
    except Exception as e:
        record("2. Schema Table Audit", False, str(e))

    # 3. Transactional Incident Lifecycle & Constraint Verification
    inc_id = f"inc-pg-{uuid.uuid4().hex[:8]}"
    now_ts = int(time.time())
    try:
        with Session() as session:
            # Create incident
            inc = IncidentModel(
                id=inc_id,
                title="PostgreSQL Live Verification Emergency",
                description="Simulated flash flood incident for M3.14 verification",
                category="FLOOD",
                priority=1,
                severity=4,
                status="REPORTED",
                source="OPERATOR",
                latitude=12.9716,
                longitude=77.5946,
                version=1,
                created_at=now_ts,
                updated_at=now_ts
            )
            session.add(inc)
            session.commit()

            # State transition to TRIAGED
            inc.status = "TRIAGED"
            inc.updated_at = int(time.time())
            session.commit()

            # State transition to RESPONDING
            inc.status = "RESPONDING"
            inc.updated_at = int(time.time())
            session.commit()

            # Verify in fresh query
            fetched = session.query(IncidentModel).filter_by(id=inc_id).first()
            assert fetched is not None
            assert fetched.status == "RESPONDING", f"Expected RESPONDING, got {fetched.status}"
            assert fetched.incident_number is not None, f"Expected autogenerated incident_number, got {fetched.incident_number}"
            record("3. Incident Transaction Lifecycle", True, f"Incident {inc_id} (# {fetched.incident_number}) transitioned REPORTED -> TRIAGED -> RESPONDING")
    except Exception as e:
        record("3. Incident Transaction Lifecycle", False, str(e))

    # 4. Responder Registration, Team & Dispatch Assignment with Partial Index
    resp_id = f"resp-pg-{uuid.uuid4().hex[:8]}"
    team_id = f"team-pg-{uuid.uuid4().hex[:8]}"
    asgn_id = f"asgn-pg-{uuid.uuid4().hex[:8]}"
    try:
        with Session() as session:
            responder = ResponderModel(
                id=resp_id,
                callsign="SAR-LEAD-ALPHA",
                responder_type="SAR",
                skills=["K9_SEARCH", "HIGH_ANGLE_RESCUE"],
                availability="AVAILABLE",
                last_latitude=12.9710,
                last_longitude=77.5940,
                created_at=int(time.time())
            )
            session.add(responder)

            team = TeamModel(
                id=team_id,
                name=f"Alpha SAR Unit {uuid.uuid4().hex[:4]}",
                callsign="ALPHA-SAR",
                status="active",
                created_at=int(time.time())
            )
            session.add(team)
            session.commit()

            member = TeamMemberModel(
                team_id=team_id,
                responder_id=resp_id,
                joined_at=int(time.time())
            )
            session.add(member)

            assignment = AssignmentModel(
                id=asgn_id,
                incident_id=inc_id,
                responder_id=resp_id,
                team_id=team_id,
                status="DISPATCHED",
                offered_at=int(time.time()),
                responded_at=None,
                completed_at=None
            )
            session.add(assignment)
            session.commit()

            # Verify PostgreSQL partial unique index prevents 2 active assignments for the same responder
            dup_asgn = AssignmentModel(
                id=f"asgn-dup-{uuid.uuid4().hex[:8]}",
                incident_id=inc_id,
                responder_id=resp_id,
                status="DISPATCHED",
                offered_at=int(time.time())
            )
            session.add(dup_asgn)
            partial_index_blocked = False
            try:
                session.commit()
            except Exception:
                session.rollback()
                partial_index_blocked = True

            assert partial_index_blocked, "Partial unique index uq_assignments_active_responder failed to enforce single active assignment!"

            # Complete assignment cleanly
            asgn_to_update = session.query(AssignmentModel).filter_by(id=asgn_id).first()
            asgn_to_update.status = "COMPLETED"
            asgn_to_update.completed_at = int(time.time())
            session.commit()

            record("4. Responder, Dispatch & Partial Index", True, f"Responder {resp_id} assigned. Partial index uq_assignments_active_responder strictly enforced.")
    except Exception as e:
        record("4. Responder, Dispatch & Partial Index", False, str(e))

    # 5. Transactional Outbox Event Persistence and Processing
    outbox_id = f"out-{uuid.uuid4().hex[:8]}"
    try:
        with Session() as session:
            out_evt = OutboxEventModel(
                event_id=outbox_id,
                aggregate_type="incident",
                aggregate_id=inc_id,
                aggregate_version=1,
                event_type="incident.dispatched",
                payload={"incident_id": inc_id, "assignment_id": asgn_id, "actor_id": "op_test"},
                created_at=int(time.time()),
                retry_count=0
            )
            session.add(out_evt)
            session.commit()

            # Process outbox batch using the actual publisher service
            published_list = process_outbox_batch(session)
            session.commit()

            # Check status and monotonic stream sequence
            processed_evt = session.query(OutboxEventModel).filter_by(event_id=outbox_id).first()
            assert processed_evt.published_at is not None, "Outbox event published_at was not populated!"
            
            stream_evt = session.query(StreamEventModel).filter_by(event_id=outbox_id).first()
            assert stream_evt is not None, "Stream event was not inserted!"
            assert stream_evt.stream_seq >= 1, f"Expected valid monotonic stream_seq, got {stream_evt.stream_seq}"

            record("5. Transactional Outbox Pipeline", True, f"Outbox event processed. StreamEvent seq={stream_evt.stream_seq} in PostgreSQL.")
    except Exception as e:
        record("5. Transactional Outbox Pipeline", False, str(e))

    # 6. Live API TestClient Verification against PostgreSQL
    try:
        client = TestClient(app)
        # Ensure operator user exists in database
        op_username = f"op_{uuid.uuid4().hex[:6]}"
        with Session() as session:
            op_user = UserModel(
                username=op_username,
                email=f"{op_username}@rescuemesh.local",
                password_hash=hash_password("DevPass123!"),
                role="DISPATCHER",
                status="active",
                is_active=True,
                created_at=int(time.time())
            )
            session.add(op_user)
            session.commit()
            token = create_access_token(
                user_id=op_user.id,
                username=op_user.username,
                role="dispatcher",
                token_version=op_user.token_version
            )

        headers = {"Authorization": f"Bearer {token}"}

        # Query incidents via API
        r = client.get("/api/v1/incidents", headers=headers)
        assert r.status_code == 200, f"GET /incidents returned {r.status_code}: {r.text}"
        incidents = r.json()
        assert any(i["id"] == inc_id for i in incidents), f"Created incident {inc_id} not found in API response"

        # Query health check
        r_health = client.get("/health")
        assert r_health.status_code == 200, f"GET /health returned {r_health.status_code}"
        health_data = r_health.json()
        assert health_data.get("status") in ("ok", "healthy"), f"Unexpected health status: {health_data}"

        record("6. Live FastAPI API Endpoints", True, f"API query succeeded on live PG. Incidents: {len(incidents)}. Health: {health_data.get('status')}")
    except Exception as e:
        record("6. Live FastAPI API Endpoints", False, str(e))

    # 7. Database Container Restart and Reconnect Recovery
    try:
        print("Testing container restart & reconnect...")
        subprocess.run(["docker", "stop", "rescuemesh-postgres"], check=True, capture_output=True)
        # Verify downtime
        down_engine = create_engine(PG_URL, pool_pre_ping=False)
        is_down = False
        try:
            with down_engine.connect() as c:
                c.execute(text("SELECT 1;"))
        except Exception:
            is_down = True
        assert is_down, "Expected database to be unreachable while stopped"

        # Restart container
        subprocess.run(["docker", "start", "rescuemesh-postgres"], check=True, capture_output=True)
        
        # Poll for readiness
        reconnected = False
        for _ in range(20):
            time.sleep(1)
            try:
                with engine.connect() as c:
                    val = c.execute(text("SELECT 1;")).scalar()
                    if val == 1:
                        reconnected = True
                        break
            except Exception:
                pass
        assert reconnected, "Database failed to recover within 20 seconds after restart"

        # Verify persistent data survived restart
        with Session() as session:
            inc_post_restart = session.query(IncidentModel).filter_by(id=inc_id).first()
            assert inc_post_restart is not None, "Data was lost across container restart!"
            assert inc_post_restart.status == "RESPONDING"

        record("7. Container Restart & Reconnect Recovery", True, f"Container restarted cleanly. Persistent incident {inc_id} verified intact.")
    except Exception as e:
        record("7. Container Restart & Reconnect Recovery", False, str(e))

    # 8. Live Backup and Restore Verification
    backup_file = "rescuemesh_m3_14_verify_backup.sql"
    restore_db = "rescuemesh_verify_restore"
    try:
        print("Testing live pg_dump backup and restore...")
        # pg_dump via docker exec
        dump_proc = subprocess.run(
            ["docker", "exec", "rescuemesh-postgres", "pg_dump", "-U", "rescuemesh", "rescuemesh"],
            capture_output=True,
            check=True
        )
        with open(backup_file, "wb") as f:
            f.write(dump_proc.stdout)
        file_size = os.path.getsize(backup_file)
        assert file_size > 1000, f"Backup file unexpectedly small: {file_size} bytes"

        # Drop restore_db if exists from prior run, then create
        subprocess.run(
            ["docker", "exec", "rescuemesh-postgres", "dropdb", "-U", "rescuemesh", "--if-exists", restore_db],
            capture_output=True
        )
        subprocess.run(
            ["docker", "exec", "rescuemesh-postgres", "createdb", "-U", "rescuemesh", restore_db],
            capture_output=True,
            check=True
        )

        # Restore into temporary database
        restore_proc = subprocess.run(
            ["docker", "exec", "-i", "rescuemesh-postgres", "psql", "-U", "rescuemesh", "-d", restore_db],
            input=dump_proc.stdout,
            capture_output=True,
            check=True
        )

        # Count incidents in restored DB
        count_proc = subprocess.run(
            ["docker", "exec", "rescuemesh-postgres", "psql", "-U", "rescuemesh", "-d", restore_db, "-t", "-c", "SELECT count(*) FROM incidents;"],
            capture_output=True,
            text=True,
            check=True
        )
        restored_count = int(count_proc.stdout.strip())
        assert restored_count >= 1, f"Expected at least 1 incident in restored database, got {restored_count}"

        # Clean up temporary database and backup file
        subprocess.run(
            ["docker", "exec", "rescuemesh-postgres", "dropdb", "-U", "rescuemesh", restore_db],
            capture_output=True,
            check=True
        )
        if os.path.exists(backup_file):
            os.remove(backup_file)

        record("8. Backup (pg_dump) & Restore Verification", True, f"pg_dump ({file_size} bytes) restored into {restore_db}. Verified {restored_count} incidents.")
    except Exception as e:
        record("8. Backup (pg_dump) & Restore Verification", False, str(e))
        subprocess.run(["docker", "exec", "rescuemesh-postgres", "dropdb", "-U", "rescuemesh", "--if-exists", restore_db], capture_output=True)
        if os.path.exists(backup_file):
            os.remove(backup_file)

    print("=" * 70)
    summary_passed = sum(1 for r in results if r["passed"])
    print(f"VERIFICATION SUMMARY: {summary_passed}/{len(results)} SUCCEEDED")
    print("=" * 70)

    if summary_passed != len(results):
        sys.exit(1)

if __name__ == "__main__":
    main()
